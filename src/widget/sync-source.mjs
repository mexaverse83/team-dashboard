#!/usr/bin/env node
// Regenerates finance-widget.source.ts from finance-widget.js, so the
// widget-code route bundles the script as a string instead of reading a file
// at runtime (which Vercel's file tracing could leave out).
//
//   node src/widget/sync-source.mjs
//
// tests/lib/widget-code.test.ts fails when the two drift apart.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))

export function renderSourceModule(code) {
  return [
    '// Generated by src/widget/sync-source.mjs from finance-widget.js. Do not edit.',
    `export const WIDGET_SOURCE: string = ${JSON.stringify(code)}`,
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const code = readFileSync(join(here, 'finance-widget.js'), 'utf8')
  writeFileSync(join(here, 'finance-widget.source.ts'), renderSourceModule(code))
  console.log('wrote src/widget/finance-widget.source.ts')
}
